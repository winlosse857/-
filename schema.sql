-- Run this script in Supabase SQL Editor.
create table if not exists public.bot_settings (
    id bigint primary key,
    owner_telegram_id bigint unique,
    channel_id text,
    channel_title text,
    channel_username text,
    timezone text not null default 'Europe/Moscow',
    created_at timestamptz not null default now()
);

-- A single settings row (id=1) is used for this private bot.
create table if not exists public.scheduled_posts (
    id bigint generated by default as identity primary key,
    owner_telegram_id bigint not null,
    channel_id text not null,
    content text not null,
    media jsonb not null default '[]'::jsonb,
    publish_at timestamptz not null,
    recurrence text not null default 'once' check (recurrence in ('once', 'daily')),
    status text not null default 'pending'
      check (status in ('pending', 'publishing', 'published', 'failed', 'cancelled')),
    created_at timestamptz not null default now(),
    published_at timestamptz,
    error text
);

create index if not exists scheduled_posts_due_idx
on public.scheduled_posts (publish_at)
where status = 'pending';

